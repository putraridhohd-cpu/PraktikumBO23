package Jobsheet2.Tugas3;

public class Lingkaran23 {
    public double phi;
    public double r;

    // method buat hitung luas lingkaran
    public double hitungLuas() {
        return phi * r * r;

    }

    // method buat hitung kelilimg lingkaran 
    public double hitungKeliling() {
        return 2 * phi * r;
    }
}
